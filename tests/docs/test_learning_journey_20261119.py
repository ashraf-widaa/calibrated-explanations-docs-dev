"""The five-step learning journey stays continuous: each step says where it is and links onward.

Journey: Quick Start -> CE by example -> Python walkthrough -> How to read CE explanations
-> Apply CE to your own data -> Evaluate CE on your own data. CE by example and the
walkthrough are generated by scripts/docs/build_quickstart_walkthrough.py.
"""

from __future__ import annotations

from pathlib import Path

import pytest

DOCS = Path(__file__).resolve().parents[2] / "docs"
JOURNEY = [
    ("get-started/ce-by-example.md", 1, "quickstart_walkthrough.md"),
    ("get-started/quickstart_walkthrough.md", 2, "interpret_explanations.md"),
    ("foundations/how-to/interpret_explanations.md", 3, "get-started/apply-to-your-data"),
    ("get-started/apply-to-your-data.md", 4, "practitioner/evaluate_ce"),
    ("practitioner/evaluate_ce.md", 5, "sections/how-ce-works"),
]


@pytest.mark.parametrize(("page", "step", "next_target"), JOURNEY)
def test_each_step_states_its_position_and_links_onward(page: str, step: int, next_target: str) -> None:
    text = " ".join((DOCS / page).read_text(encoding="utf-8").split())
    assert f"step {step} of 5" in text, page
    assert next_target in text, (page, next_target)


def test_generator_owns_the_journey_text_of_generated_pages() -> None:
    generator = (DOCS.parent / "scripts" / "docs" / "build_quickstart_walkthrough.py").read_text(encoding="utf-8")
    assert "Learning journey, step 1 of 5." in generator
    assert "Learning journey, step 2 of 5." in generator
    assert "Next in the learning journey (step 3 of 5):" in generator
