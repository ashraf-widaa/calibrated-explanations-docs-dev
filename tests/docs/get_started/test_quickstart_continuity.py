"""Quick Start continuity: three paths in, and onward routes out.

The walkthrough page is generated by ``scripts/docs/build_quickstart_walkthrough.py``;
its static "Where to go next" table must stay identical in the generator and the page,
and must offer routes to the methods page and to Software & Integration. The
landing page offers paths A, B and C (B = the code-free "CE by example"), and Path C
pages keep their key structure.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
GENERATOR = ROOT / "scripts" / "docs" / "build_quickstart_walkthrough.py"
PAGE = ROOT / "docs" / "get-started" / "quickstart_walkthrough.md"
NOTEBOOK = ROOT / "docs" / "_static" / "notebooks" / "quickstart_walkthrough.ipynb"
INDEX = ROOT / "docs" / "get-started" / "index.md"


def next_step_rows(text: str) -> list[str]:
    section = text.split("### Where to go next", 1)[1]
    return [line.strip() for line in section.splitlines() if line.startswith("| ") and "](" in line]


def test_generator_and_page_share_the_same_next_steps() -> None:
    generator_rows = next_step_rows(GENERATOR.read_text(encoding="utf-8"))
    page_rows = next_step_rows(PAGE.read_text(encoding="utf-8"))
    assert generator_rows == page_rows


def test_next_steps_reach_methods_and_software_integration() -> None:
    rows = " ".join(next_step_rows(PAGE.read_text(encoding="utf-8")))
    assert "foundations/concepts/calibration_methods.md" in rows
    assert "sections/software-integration.md" in rows


def test_notebook_carries_the_same_number_of_next_step_rows() -> None:
    notebook = NOTEBOOK.read_text(encoding="utf-8")
    page_rows = next_step_rows(PAGE.read_text(encoding="utf-8"))
    for row in page_rows:
        label = row.split("|")[1].strip()
        assert f"| {label} |" in notebook, label


def test_quick_start_landing_offers_three_paths_in_order() -> None:
    text = INDEX.read_text(encoding="utf-8").replace("\r\n", "\n")
    cards = re.findall(r":::\{grid-item-card\} ([ABC]) · [^\n]*\n:link: ([^\n]+)", text)
    assert cards == [
        ("A", "why-ce"),
        ("B", "ce-by-example"),
        ("C", "ce-tasks-and-modes"),
    ]
    assert "A \u2192 B \u2192 C" in text
    assert 'srcset="../_static/figures/ce-at-a-glance-narrow.svg"' in text
    assert 'src="../_static/figures/ce-at-a-glance.svg"' in text


